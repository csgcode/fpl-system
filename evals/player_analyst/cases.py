@dataclass(frozen=True)
class ReplayCase:
    """`work_calls` and `handback` pin what the parser must find in the
    frozen transcript."""

    id: str
    agent: str
    gw: int
    pos: str
    work_calls: int
    handback: bool
    mode: str = NORMAL
    top15_call: int | None = None
    """The work call whose `ep` stdout lists the run's own top 15, when the
    committed players json was later regenerated by another run."""
    pre_reopen_inputs: bool = False

    @property
    def fixture(self) -> Path:
        return FIXTURES / "replay" / f"{self.id}.jsonl"

    @property
    def source(self) -> str:
        return f"{SESSIONS[self.gw]}/subagents/{self.agent}.jsonl"

    @property
    def commit(self) -> str:
        return CASE_COMMITS[self.gw]

    @property
    def bootstrap(self) -> RepoFile:
        return GW5_REOPEN_BOOTSTRAP if self.mode == REOPEN else ANALYSIS_BOOTSTRAPS[self.gw]


