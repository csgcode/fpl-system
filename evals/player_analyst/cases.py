def git_show(commit: str, path: str, repo: Path = REPO_ROOT) -> bytes | None:
    blob = subprocess.run(["git", "-C", str(repo), "show", f"{commit}:{path}"],
                          capture_output=True, check=False)
    return blob.stdout if blob.returncode == 0 else None
