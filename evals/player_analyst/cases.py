@dataclass(frozen=True)
class Expect:
    """Case-specific outcomes beyond the generic checks. `max_gw0`/`min_gw0`
    bound p_start_gw[0] by id; `zero_ids` must be ≤ 0.05 in every gameweek;
    `falls` maps an id to (later index, earlier index) where the later value
    must be lower; `cites` maps an id to text its notes must contain."""

    max_gw0: Mapping[int, float] = field(default_factory=dict)
    min_gw0: Mapping[int, float] = field(default_factory=dict)
    zero_ids: tuple[int, ...] = ()
    guess_ids: tuple[int, ...] = ()
    falls: Mapping[int, tuple[int, int]] = field(default_factory=dict)
    cites: Mapping[int, str] = field(default_factory=dict)
    max_summary_calls: int | None = None
    summaries_for_starters: bool = False
    shunned: tuple[str, ...] = ()
    compliance_line: tuple[str, str] | None = None


@dataclass(frozen=True)
class LiveCase:
    """`run_start` is when the recorded run began: only summaries fetched
    before it are in the workspace, the rest stay fetchable through the
    replay recordings. `clock` pins the CLI's clock (default: run_start)."""

    id: str
    gw: int
    pos: str
    today: str
    run_start: str
    expect: Expect = field(default_factory=Expect)
    mode: str = NORMAL
    research: bool = False
    budget_usd: float = 3.00
    full: bool = False
    clock: str | None = None
    injection: bool = False


